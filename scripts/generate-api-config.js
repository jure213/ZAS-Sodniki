#!/usr/bin/env node

// Writes electron/generated/api-config.ts with the API base URL.
// The app ships no key: users authenticate with the login() RPC.

const fs = require("fs");
const path = require("path");

const DEFAULT_API_URL = "https://sodniki-api.jurer.eu";

const projectRoot = path.resolve(__dirname, "..");
const envPath = path.join(projectRoot, ".env");
const generatedDir = path.join(projectRoot, "electron", "generated");
const outputPath = path.join(generatedDir, "api-config.ts");

function readEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  return Object.fromEntries(
    fs
      .readFileSync(filePath, "utf8")
      .split(/\r?\n/)
      .filter((line) => line && !line.trimStart().startsWith("#") && line.includes("="))
      .map((line) => {
        const separator = line.indexOf("=");
        return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
      }),
  );
}

const apiUrl = process.env.ZAS_API_URL || readEnv(envPath).ZAS_API_URL || DEFAULT_API_URL;

let parsedUrl;
try {
  parsedUrl = new URL(apiUrl);
} catch {
  console.error("ZAS_API_URL is not a valid URL.");
  process.exit(1);
}

if (parsedUrl.protocol !== "https:" && parsedUrl.hostname !== "localhost") {
  console.error("ZAS_API_URL must use HTTPS outside localhost.");
  process.exit(1);
}

fs.mkdirSync(generatedDir, { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-api-config.js.\nexport const API_URL = ${JSON.stringify(apiUrl.replace(/\/$/, ""))};\n`,
);
console.log(`Generated ${path.relative(projectRoot, outputPath)} (${parsedUrl.origin}).`);
